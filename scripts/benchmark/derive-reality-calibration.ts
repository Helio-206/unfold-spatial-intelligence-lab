// Derives the product's declared tolerances and the consistency threshold from the DEVELOPMENT split only, and writes src/living/reality/calibration.ts.
// The acceptance split is never read here; it is used afterwards to check the constants (see reports/reality-engine/REPORT.md).
//   npx tsx scripts/benchmark/derive-reality-calibration.ts
import { readFile, writeFile } from 'node:fs/promises';
const data = JSON.parse(await readFile('reports/reality-engine/benchmark/results/results.json', 'utf8')) as { results: Array<{ id: string; split: string; sets: Record<string, { chamferPct: number; p95AccuracyPct: number; looIoUMean: number | null; looIoUMeanWrongPoses: number | null }> }> };
const dev = data.results.filter((r) => r.split === 'development');
const sets = ['2-view', '3-view-ortho', '6-view', '12-view'], views: Record<string, number> = { '2-view': 2, '3-view-ortho': 3, '6-view': 6, '12-view': 12 };
const table = sets.map((s) => {
  const ch = dev.map((r) => r.sets[s]!.chamferPct), p95 = dev.map((r) => r.sets[s]!.p95AccuracyPct);
  return { views: views[s]!, chamferPctMax: +Math.max(...ch).toFixed(2), chamferPctMedian: +[...ch].sort((a, b) => a - b)[Math.floor(ch.length / 2)]!.toFixed(2), p95AccuracyPctMax: +Math.max(...p95).toFixed(2) };
});
const correct = dev.flatMap((r) => ['6-view', '12-view'].map((s) => r.sets[s]!.looIoUMean!));
const threshold = Math.floor((Math.min(...correct) - 0.05) * 100) / 100;
const text = `// GENERATED by scripts/benchmark/derive-reality-calibration.ts from the DEVELOPMENT split of reports/reality-engine/benchmark/results/results.json. Do not edit by hand.
// Source of the numbers: RENDERED views of ${dev.length} independent licensed 3D assets (${dev.map((r) => r.id).join(', ')}); distances are % of the bounding-box diagonal.
// They describe the geometry engine on clean silhouettes with known cameras. They are NOT validated on photographs.
export const HULL_ERROR_BY_VIEW_COUNT = ${JSON.stringify(table, null, 2)} as const;
/** Held-out (leave-one-out) silhouette agreement below this is reported as a failed consistency check: min over development sets with correct poses, minus 0.05. */
export const CONSISTENCY_THRESHOLD = ${threshold};
export const CALIBRATION_SOURCE = 'development split, rendered views, benchmark manifest v1';
`;
await writeFile('src/living/reality/calibration.ts', text);
